import { chromium } from '@playwright/test';
import { login } from '../helpers/loginHelper.js';
const out = 'reports/aqi-weather/explore';
const b = await chromium.launch(); const ctx = await b.newContext({viewport:{width:1440,height:900}});
const page = await ctx.newPage();
const reqs=[]; const cons=[];
page.on('console', m=>{ if(['error','warning'].includes(m.type())) cons.push(`${m.type()}: ${m.text().slice(0,200)}`)});
page.on('response', r=>{ const u=r.url(); if(!/\.(png|jpg|svg|css|woff2?|js)(\?|$)/.test(u)) reqs.push(`${r.request().method()} ${r.status()} ${u.slice(0,160)}`)});
await login(page);
await page.goto('https://cms.pocsample.in/library',{waitUntil:'domcontentloaded'});
await page.waitForFunction(()=>document.body.innerText.length>200,null,{timeout:60000}).catch(()=>{});
await page.waitForTimeout(3000);
await page.screenshot({path:`${out}/02a-library.png`});
console.log('URL',page.url());
console.log((await page.locator('body').innerText()).slice(0,800));
const w = page.getByText(/^Widgets (d+)$/).first();
await w.click({timeout:15000}).catch(e=>console.log('click fail',e.message.slice(0,100)));
await page.waitForTimeout(5000);
await page.screenshot({path:`${out}/02-widgets.png`,fullPage:true});
console.log('--- WIDGETS PAGE'); console.log((await page.locator('body').innerText()).slice(0,3500));
console.log('--- REQS'); console.log([...new Set(reqs)].join('\n'));
console.log('--- CONSOLE'); console.log(cons.join('\n'));
await b.close();
