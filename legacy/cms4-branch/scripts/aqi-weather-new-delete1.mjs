import { chromium } from '@playwright/test';
import fs from 'fs';
const env = Object.fromEntries(fs.readFileSync('.env','utf8').split(/\r?\n/).filter(l=>/^[A-Z_]+=/.test(l)).map(l=>[l.split('=')[0],l.slice(l.indexOf('=')+1).trim()]));
const b=await chromium.launch(); const page=await (await b.newContext({viewport:{width:1440,height:900}})).newPage();
page.on('request',r=>{ if(/widget\/(delete|remove)|DELETE/i.test(r.method()+r.url())&&/widget/.test(r.url())) console.log('REQ',r.method(),r.url(),(r.postData()||'').slice(0,200)) });
page.on('response',async r=>{ if(r.request().method()==='DELETE'||/widget\/delete/.test(r.url())) console.log('RES',r.status(),(await r.text()).slice(0,200)) });
page.on('dialog',d=>d.accept());
await page.goto('https://cms.pocsample.in',{waitUntil:'domcontentloaded'});
await page.getByRole('textbox',{name:/email|phone/i}).fill(env.CMS_ADMIN_EMAIL);
await page.getByRole('textbox',{name:/password/i}).fill(env.CMS_ADMIN_PASSWORD);
await page.getByRole('button',{name:/log in/i}).click(); await page.waitForTimeout(8000);
await page.goto('https://cms.pocsample.in/library',{waitUntil:'domcontentloaded'});
await page.waitForFunction(()=>/Widgets \(/.test(document.body.innerText),null,{timeout:60000});
await page.getByText(/^Widgets [(][0-9]+[)]$/).first().click(); await page.waitForTimeout(2500);
await page.getByText(/^Weather [(][0-9]+[)]$/).first().click(); await page.waitForTimeout(3000);
const s=page.getByRole('textbox',{name:/^search/i}).last(); await s.fill('QA_CMP_'); await page.waitForTimeout(2000);
const rows=page.locator('p',{hasText:/^QA_CMP_/}); console.log('QA_CMP rows:',await rows.count(), await rows.allInnerTexts());
const row=rows.first().locator('xpath=..'); await row.getByRole('button').nth(1).click(); await page.waitForTimeout(1500);
const c=page.getByRole('button',{name:/^(yes|delete|confirm|ok)$/i}); if(await c.first().isVisible().catch(()=>false)) await c.first().click();
await page.waitForTimeout(3000);
await s.fill('QA_CMP_'); await page.waitForTimeout(2000);
console.log('after delete rows:',await page.locator('p',{hasText:/^QA_CMP_/}).count());
await b.close();
