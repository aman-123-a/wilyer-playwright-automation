import { chromium } from '@playwright/test';
import fs from 'fs';
const env = Object.fromEntries(fs.readFileSync('.env','utf8').split(/\r?\n/).filter(l=>/^[A-Z_]+=/.test(l)).map(l=>[l.split('=')[0],l.slice(l.indexOf('=')+1).trim()]));
const out='reports/aqi-weather-api-comparison/explore';
const b=await chromium.launch(); const page=await (await b.newContext({viewport:{width:1440,height:900}})).newPage();
page.on('request',r=>{ if(/widget\/(create|update)/.test(r.url())){ const h=r.headers(); console.log('REQ',r.method(),r.url(),'\nBODY',(r.postData()||'').slice(0,800),'\nHDRS',Object.keys(h).join(',')) } });
page.on('response',async r=>{ if(/widget\/create/.test(r.url())) console.log('RES',r.status(),(await r.text()).slice(0,400)) });
await page.goto('https://cms.pocsample.in',{waitUntil:'domcontentloaded'});
await page.getByRole('textbox',{name:/email|phone/i}).fill(env.CMS_ADMIN_EMAIL);
await page.getByRole('textbox',{name:/password/i}).fill(env.CMS_ADMIN_PASSWORD);
await page.getByRole('button',{name:/log in/i}).click(); await page.waitForTimeout(8000);
await page.goto('https://cms.pocsample.in/library',{waitUntil:'domcontentloaded'});
await page.waitForFunction(()=>/Widgets \(/.test(document.body.innerText),null,{timeout:60000});
await page.getByText(/^Widgets [(][0-9]+[)]$/).first().click(); await page.waitForTimeout(2500);
await page.getByText(/^Weather [(][0-9]+[)]$/).first().click(); await page.waitForTimeout(3000);
await page.getByRole('button',{name:/add new/i}).click();
const d=page.getByRole('dialog');
await d.locator('input[name="name"]').fill('QA_CMP_weather_delhi');
await d.locator('input[name="city1"]').first().fill('Delhi'); await page.waitForTimeout(2500);
await page.screenshot({path:out+'/new-weather-autocomplete.png'});
console.log('pac items:', await page.locator('.pac-item').count());
await page.locator('.pac-item').first().click().catch(async()=>{ await page.keyboard.press('ArrowDown'); await page.keyboard.press('Enter'); });
await page.waitForTimeout(1000);
await d.getByRole('button',{name:/^save$/i}).click(); await page.waitForTimeout(5000);
await page.screenshot({path:out+'/new-weather-after-save.png'});
await b.close();
