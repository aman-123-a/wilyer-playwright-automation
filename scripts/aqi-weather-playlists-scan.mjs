import { chromium } from '@playwright/test';
import { login } from '../helpers/loginHelper.js';
import fs from 'fs';
const out='reports/aqi-weather-playlists';
const b=await chromium.launch(); const ctx=await b.newContext();
const page=await ctx.newPage();
let hdr=null;
page.on('request',r=>{if(r.url().includes('/v3/cms/playlist/read')&&!hdr)hdr=r.headers()});
await login(page);
await page.goto('https://cms.pocsample.in/playlists',{waitUntil:'domcontentloaded'});
await page.waitForTimeout(6000);
const h={}; for(const k of ['authorization','token','x-auth-token','cookie'])if(hdr[k])h[k]=hdr[k];
console.log('hdr keys',Object.keys(hdr).join(','));
let all=[],p=1,tp=1;
do{const r=await ctx.request.get(`https://v3-5api.pocsample.in/v3/cms/playlist/read?page=${p}&search=&limit=50&sort=createdAt&order=-1&isNotFolder=false`,{headers:hdr});
 const j=await r.json(); all.push(...j.docs); tp=j.totalPages; p++;}while(p<=tp);
fs.writeFileSync(`${out}/all-playlists.json`,JSON.stringify(all));
const hits=all.filter(d=>(d.layouts||[]).some(l=>(l.zones||[]).some(z=>/widgets\/(aqi|weather)/i.test(z.img||''))));
console.log('total',all.length,'hits',hits.length);
for(const d of hits)console.log(d.id,d.name,d.screens,(d.layouts||[]).map((l,i)=>i+':'+l.zones.map(z=>(z.img||'').split('/').pop()).join('|')).join(' ; '));
await b.close();
